class McasmDAGToDAGISel : public SelectionDAGISel {
  const McasmSubtarget *Subtarget = nullptr;

public:
  McasmDAGToDAGISel() = delete;

  explicit McasmDAGToDAGISel(McasmTargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISel(TM, OptLevel) {
    MCASM_DEBUG_LOG("DEBUG: McasmDAGToDAGISel constructor completed\n");
  }

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<McasmSubtarget>();
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

  bool SelectInlineAsmMemoryOperand(const SDValue &Op,
                                    InlineAsm::ConstraintCode ConstraintCode,
                                    std::vector<SDValue> &OutOps) override;

  void Select(SDNode *N) override;

  StringRef getPassName() const { return PASS_NAME; }

  // Variables needed by TableGen-generated code
  bool EnablePromoteAnyextLoad = false;

  // Include the pieces autogenerated from the target description.
#include "McasmGenDAGISel.inc"

private:
  bool SelectAddr(SDNode *Parent, SDValue N, SDValue &Base, SDValue &Scale,
                  SDValue &Index, SDValue &Disp, SDValue &Segment);
  bool selectAddr(SDNode *Parent, SDValue N, SDValue &Base, SDValue &Scale,
                  SDValue &Index, SDValue &Disp, SDValue &Segment) {
    return SelectAddr(Parent, N, Base, Scale, Index, Disp, Segment);
  }
};

